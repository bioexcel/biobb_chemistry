# type: ignore
from biobb_chemistry.babelm.common import remove_non_pdbqt_records

# PDBQT written by Open Babel 3.2 from a PDB with COMPND and AUTHOR records
PDBQT = """REMARK  Name = ligand.pdb
COMPND    STI.sdf
AUTHOR    GENERATED BY OPEN BABEL 2.4.1
REMARK  1 active torsions:
ROOT
ATOM      1  C   UNL     1       2.740  -0.022   8.889  0.00  0.00    +0.000 C
ENDROOT
BRANCH   1   2
ATOM      2  N   UNL     1       3.020   1.310   8.512  0.00  0.00    +0.000 NA
ENDBRANCH   1   2
TORSDOF 1
"""


class TestRemoveNonPdbqtRecords():
    def test_pdbqt_output(self, tmp_path):
        path = tmp_path / "ligand.pdbqt"
        path.write_text(PDBQT)
        remove_non_pdbqt_records("pdbqt", str(path), None)
        assert path.read_text() == "".join(line for line in PDBQT.splitlines(keepends=True) if not line.startswith(("COMPND", "AUTHOR")))

    def test_format_from_extension(self, tmp_path):
        path = tmp_path / "ligand.pdbqt"
        path.write_text(PDBQT)
        remove_non_pdbqt_records("", str(path), None)
        assert "COMPND" not in path.read_text()

    def test_other_formats_untouched(self, tmp_path):
        path = tmp_path / "ligand.pdb"
        path.write_text(PDBQT)
        remove_non_pdbqt_records("pdb", str(path), None)
        assert path.read_text() == PDBQT
